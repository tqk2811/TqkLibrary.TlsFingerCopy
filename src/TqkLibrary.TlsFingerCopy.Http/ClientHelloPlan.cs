using System.Buffers.Binary;
using System.Net;
using System.Security.Cryptography;
using System.Text;
using TqkLibrary.TlsFingerCopy.Helpers;
using TqkLibrary.TlsFingerCopy.Models;

namespace TqkLibrary.TlsFingerCopy.Http;

/// <summary>
/// The ClientHello content of ONE connection, derived from a recorded <see cref="TlsFingerprint"/>:
/// fresh GREASE values, SNI of the real host, fresh GREASE ECH payload, optional per-connection extension shuffle.
/// </summary>
/// <remarks>
/// Extensions BC builds itself are not placed in <see cref="Extensions"/> but still positioned by
/// <see cref="ExtensionOrder"/>: supported_versions (43, from <see cref="ProtocolVersions"/>), key_share (51, from
/// <see cref="KeyShareGroups"/>) and extended_master_secret (23, see <see cref="UseExtendedMasterSecret"/>).
/// <para>Every other recorded extension is copied raw (same bytes as recorded), except:</para>
/// <list type="bullet">
/// <item>GREASE extensions: new GREASE type, recorded data.</item>
/// <item>server_name (0): rebuilt for the real host; dropped for IP literals.</item>
/// <item>supported_groups (10) / signature_algorithms (13): GREASE entries replaced by this connection's GREASE.</item>
/// <item>padding (21): sized by BC (BoringSSL rule).</item>
/// <item>session_ticket (35): always sent EMPTY (no ticket is ever resumed).</item>
/// <item>pre_shared_key (41), early_data (42), cookie (44): dropped (only valid for resumption / a HelloRetryRequest retry).</item>
/// <item>encrypted_client_hello (0xfe0d): GREASE ECH with fresh config_id, enc and payload (header kept);
/// dropped when the recorded data is not a reproducible ECH outer structure.</item>
/// </list>
/// </remarks>
internal class ClientHelloPlan
{
    internal const int ServerNameType = 0;
    internal const int SupportedGroupsType = 10;
    internal const int SignatureAlgorithmsType = 13;
    internal const int PaddingType = 21;
    internal const int ExtendedMasterSecretType = 23;
    internal const int SessionTicketType = 35;
    internal const int PreSharedKeyType = 41;
    internal const int EarlyDataType = 42;
    internal const int SupportedVersionsType = 43;
    internal const int CookieType = 44;
    internal const int KeyShareType = 51;
    internal const int AlpsOldType = 17513;
    internal const int AlpsType = 17613;
    internal const int EncryptedClientHelloType = 0xfe0d;

    public ClientHelloPlan(TlsFingerprint fingerprint, string host)
    {
        ArgumentNullException.ThrowIfNull(fingerprint);
        var grease = new GreaseValueGenerator();

        CipherSuites = fingerprint.CipherSuites.Select(x => GreaseHelper.IsGrease(x) ? grease.CipherSuite : (int)x).ToArray();

        var versions = fingerprint.SupportedVersions.Count > 0
            ? fingerprint.SupportedVersions
            : new List<ushort> { fingerprint.LegacyVersion == 0 ? (ushort)0x0303 : fingerprint.LegacyVersion };
        ProtocolVersions = versions.Select(x => GreaseHelper.IsGrease(x) ? grease.Version : x).ToArray();

        KeyShareGroups = fingerprint.KeyShareGroups.Select(x => GreaseHelper.IsGrease(x) ? grease.Group : (int)x).ToList();

        var order = new List<int>();
        foreach (var entry in fingerprint.Extensions)
        {
            int type = entry.Type;
            byte[] data = Convert.FromHexString(entry.DataHex);
            if (GreaseHelper.IsGrease(entry.Type))
            {
                type = grease.NextExtension();
                Extensions[type] = data;
                order.Add(type);
                continue;
            }

            switch (type)
            {
                case ServerNameType:
                    byte[]? sni = BuildServerName(host);
                    if (sni is null) continue; // IP literal: browsers send no SNI
                    Extensions[type] = sni;
                    break;
                case SupportedGroupsType:
                    Extensions[type] = ReplaceGreaseU16List(data, 2, grease.Group);
                    break;
                case SignatureAlgorithmsType:
                    Extensions[type] = ReplaceGreaseU16List(data, 2, grease.SignatureAlgorithm);
                    break;
                case PaddingType:
                    // Sized by BC (BoringSSL rule), see ShouldUseBoringSslPadding.
                    Extensions[type] = Array.Empty<byte>();
                    UsePadding = true;
                    break;
                case ExtendedMasterSecretType:
                    UseExtendedMasterSecret = true;
                    break;
                case SupportedVersionsType:
                case KeyShareType:
                    break; // generated by BC
                case SessionTicketType:
                    Extensions[type] = Array.Empty<byte>(); // never resume: an empty ticket asks for a new one
                    break;
                case PreSharedKeyType:
                case EarlyDataType:
                case CookieType:
                    continue; // no resumption; a cookie only belongs to a HelloRetryRequest retry
                case EncryptedClientHelloType:
                    byte[]? ech = RandomizeGreaseEch(data);
                    if (ech is null) continue; // not reproducible: send no ECH rather than garbage
                    Extensions[type] = ech;
                    break;
                case AlpsOldType:
                case AlpsType:
                    Extensions[type] = data;
                    AlpsExtensionType = type;
                    break;
                default:
                    Extensions[type] = data;
                    break;
            }
            order.Add(type);
        }

        if (fingerprint.ExtensionOrderRandomized) Shuffle(order);
        ExtensionOrder = order;
        SessionIdLength = fingerprint.SessionIdLength;
    }

    public int[] CipherSuites { get; }

    /// <summary>Versions for supported_versions, wire order (GREASE included).</summary>
    public ushort[] ProtocolVersions { get; }

    /// <summary>Groups that get a key share (GREASE group gets a 1-byte 0x00 share in BC).</summary>
    public IList<int> KeyShareGroups { get; }

    /// <summary>Extensions handed to BC (type → data), excluding those BC generates.</summary>
    public Dictionary<int, byte[]> Extensions { get; } = new();

    /// <summary>Wire order of all extension types (including those BC generates).</summary>
    public IList<int> ExtensionOrder { get; }

    public bool UsePadding { get; }

    public bool UseExtendedMasterSecret { get; }

    public int SessionIdLength { get; }

    /// <summary>17513 / 17613 when the fingerprint offers ALPS, else null.</summary>
    public int? AlpsExtensionType { get; }

    /// <summary>
    /// Chrome-style permutation: GREASE extensions, padding and pre_shared_key keep their slots, every other
    /// extension is shuffled over the remaining slots.
    /// </summary>
    private static void Shuffle(List<int> order)
    {
        var slots = new List<int>();
        for (int i = 0; i < order.Count; i++)
        {
            int type = order[i];
            if (GreaseHelper.IsGrease((ushort)type) || type == PaddingType || type == PreSharedKeyType) continue;
            slots.Add(i);
        }
        var values = slots.Select(i => order[i]).ToArray();
        RandomNumberGenerator.Shuffle(values.AsSpan());
        for (int i = 0; i < slots.Count; i++) order[slots[i]] = values[i];
    }

    private static byte[]? BuildServerName(string host)
    {
        string name = host.Trim('[', ']').TrimEnd('.');
        if (name.Length == 0 || IPAddress.TryParse(name, out _)) return null;
        byte[] nameBytes = Encoding.ASCII.GetBytes(name);
        byte[] data = new byte[2 + 1 + 2 + nameBytes.Length];
        BinaryPrimitives.WriteUInt16BigEndian(data, (ushort)(3 + nameBytes.Length));
        data[2] = 0; // host_name
        BinaryPrimitives.WriteUInt16BigEndian(data.AsSpan(3), (ushort)nameBytes.Length);
        nameBytes.CopyTo(data, 5);
        return data;
    }

    /// <summary>Replaces GREASE entries of a length-prefixed u16 list with <paramref name="greaseValue"/>.</summary>
    private static byte[] ReplaceGreaseU16List(byte[] data, int prefixLength, ushort greaseValue)
    {
        byte[] result = (byte[])data.Clone();
        for (int pos = prefixLength; pos + 2 <= result.Length; pos += 2)
        {
            if (GreaseHelper.IsGrease(BinaryPrimitives.ReadUInt16BigEndian(result.AsSpan(pos))))
                BinaryPrimitives.WriteUInt16BigEndian(result.AsSpan(pos), greaseValue);
        }
        return result;
    }

    /// <summary>
    /// A recorded ECH extension is a GREASE ECH (the browser had no ECH config). The recorder keeps its header
    /// (type, kdf_id, aead_id, enc length, payload length) and zeroes config_id, enc and payload. Refill those with
    /// fresh random bytes per connection as BoringSSL's GREASE ECH does; keep the cipher suite and all lengths.
    /// Returns null when the data is not a reproducible ECH outer structure (the extension is then dropped).
    /// </summary>
    private static byte[]? RandomizeGreaseEch(byte[] data)
    {
        // ECHClientHello outer: type(1)=0, kdf_id(2), aead_id(2), config_id(1), enc<0..2^16-1>, payload<1..2^16-1>
        const int HeaderLength = 1 + 2 + 2 + 1;
        byte[] result = (byte[])data.Clone();
        if (TryGetEchLengths(result, out int encLength, out int payloadLength))
        {
            RandomNumberGenerator.Fill(result.AsSpan(5, 1));
            RandomNumberGenerator.Fill(result.AsSpan(HeaderLength + 2, encLength));
            RandomNumberGenerator.Fill(result.AsSpan(HeaderLength + 2 + encLength + 2, payloadLength));
            return result;
        }

        // Legacy sample (older recorder zeroed the whole extension): rebuild BoringSSL's GREASE ECH with the same total
        // length: HKDF-SHA256 (1) / AES-128-GCM (1), 32-byte X25519 enc, random payload.
        const int EncLength = 32;
        int rebuiltPayload = data.Length - HeaderLength - 2 - EncLength - 2;
        if (rebuiltPayload < 1 || data.Any(x => x != 0)) return null;
        result[0] = 0;
        BinaryPrimitives.WriteUInt16BigEndian(result.AsSpan(1), 0x0001);
        BinaryPrimitives.WriteUInt16BigEndian(result.AsSpan(3), 0x0001);
        RandomNumberGenerator.Fill(result.AsSpan(5, 1));
        BinaryPrimitives.WriteUInt16BigEndian(result.AsSpan(HeaderLength), EncLength);
        RandomNumberGenerator.Fill(result.AsSpan(HeaderLength + 2, EncLength));
        BinaryPrimitives.WriteUInt16BigEndian(result.AsSpan(HeaderLength + 2 + EncLength), (ushort)rebuiltPayload);
        RandomNumberGenerator.Fill(result.AsSpan(HeaderLength + 2 + EncLength + 2, rebuiltPayload));
        return result;
    }

    private static bool TryGetEchLengths(byte[] data, out int encLength, out int payloadLength)
    {
        encLength = payloadLength = 0;
        if (data.Length < 6 + 2 + 2 || data[0] != 0) return false;
        if (BinaryPrimitives.ReadUInt16BigEndian(data.AsSpan(1)) == 0) return false; // kdf 0 is reserved → zeroed sample
        encLength = BinaryPrimitives.ReadUInt16BigEndian(data.AsSpan(6));
        int payloadPos = 8 + encLength;
        if (payloadPos + 2 > data.Length) return false;
        payloadLength = BinaryPrimitives.ReadUInt16BigEndian(data.AsSpan(payloadPos));
        return payloadLength > 0 && payloadPos + 2 + payloadLength == data.Length;
    }
}
